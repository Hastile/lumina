let locale: Locale = 'ko'

export function setLocale(l: Locale): void {
  locale = l
}

export function getLocale(): Locale {
  return locale
}

/** Translate; strips Windows menu accelerators (&F) outside menus. */
export function t(s: string, opts: { menu?: boolean } = {}): string {
  const out = locale === 'ko' ? ko[s] ?? s : s
  return opts.menu ? out : out.replace(/\(&\w\)/, '')
}
