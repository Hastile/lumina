import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
const out='../.tmp/mobile-monitor-check';mkdirSync(out,{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
 const errors=[],posts=[];page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{if(r.method()==='POST')posts.push(r.url())})
 await page.goto('http://100.72.70.28:8766')
 await page.waitForFunction(()=>document.querySelector('#program').naturalWidth>0,null,{timeout:60000})
 const original=await page.evaluate(async()=>await(await fetch('/api/state')).json())
 assert.ok(await page.locator('.track').count())
 assert.equal(await page.locator('#prepare').count(),0)
 await page.locator('#seek').evaluate(el=>{el.value=90;el.dispatchEvent(new Event('input',{bubbles:true}))})
 await page.waitForFunction(()=>document.querySelector('#frameStatus').textContent.includes(' · 90f')&&document.querySelector('#program').style.opacity==='1',null,{timeout:30000})
 await page.locator('#nextFrame').click()
 await page.waitForFunction(()=>document.querySelector('#time').textContent.includes(' · 91f'))
 await page.locator('#backFrame').click()
 await page.waitForFunction(()=>document.querySelector('#time').textContent.includes(' · 90f'))
 await page.locator('#fine').evaluate(el=>{for(const n of [95,100,105,110]){el.value=n;el.dispatchEvent(new Event('input',{bubbles:true}))}})
 await page.waitForFunction(()=>document.querySelector('#frameStatus').textContent.includes(' · 110f'),null,{timeout:30000})
 assert.match(await page.locator('#reference').inputValue(),/클립 ID/)
 assert.match(await page.locator('#reference').inputValue(),/110f/)
 await page.locator('#nextCut').click()
 assert.ok(!(await page.locator('#time').innerText()).includes(' · 110f'))
 await page.locator('#clipLast').click()
 await page.waitForTimeout(800)
 assert.match(await page.locator('#reference').inputValue(),/끝 제외/)
 await page.locator('#copy').click()
 assert.match(await page.locator('#copy').innerText(),/복사/)
 const final=await page.evaluate(async()=>await(await fetch('/api/state')).json())
 assert.equal(final.timeline.playhead.ticks,original.timeline.playhead.ticks)
 assert.equal(final.project.dirty,original.project.dirty)
 assert.deepEqual(posts,[]);assert.deepEqual(errors,[])
 await page.screenshot({path:out+'/phone-scrub.png',fullPage:true})
 console.log('PASS: frame stepping, latest-only scrub, cut boundary, last frame, Chat reference, no render POST, PC state unchanged')
} finally {await browser.close()}
