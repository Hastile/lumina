-- Migration 010: 녹화가 본편의 어디서 시작하는지.
--
-- 왜 media 인가
-- -------------
-- source 는 그 화 자체(원피스 1089화)라 화당 한 행입니다. 오프셋은 **이
-- 녹화 파일**의 성질입니다 - 같은 화를 두 번 녹화하면 시작 지점이 다르고,
-- source 에 두면 나중에 녹화한 쪽이 앞의 값을 덮어씁니다.
--
-- 무엇이 가능해지나
-- -----------------
-- 녹화 3초 지점의 컷은 실제로 본편 19분 10초입니다. 이 값이 없으면 컷을
-- 본편 위치로 되돌릴 방법이 없고, 있으면 모든 컷이 진짜 타임코드를
-- 갖습니다 - 원본을 다시 찾을 때도, 같은 화의 두 녹화가 겹치는지 볼 때도
-- 그 기준이 필요합니다.
--
-- NULL 이 정상입니다: 통짜 영상이나 이미지, 본편이라는 것이 없는 스톡
-- 영상에는 오프셋이 없습니다.

ALTER TABLE media ADD COLUMN source_offset_ms INTEGER;
